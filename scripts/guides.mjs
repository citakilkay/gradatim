// The user guides (REL-1): each skill's guide, docs/guides/<skill>.md, and the README's table of the cycle, written from
// the skill's own file and the cycle's table, skills/method/references/cycle.md, and nothing else. A guide's first line
// opens the block that this script writes, its end marker closes it, and the rest of the file is written by hand, such
// as a "Good to know". The README's block is its table of the cycle. scripts/check.mjs holds every block to what this
// script writes now, by guideProblems below, so that a guide can't drift from its skill.
//
// Usage, from anywhere in the repository:
//   npm run guides
// It creates a missing guide, and replaces the block in each guide and in the README. Where a file's markers are
// missing or doubled, it writes nothing and exits 1. It deletes nothing.
import { existsSync, mkdirSync, readdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, join, posix, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { cellText, relativeLinks, tablesIn, unfencedLines } from '../skills/method/scripts/check-docs.mjs';
import { parseFrontmatter } from './frontmatter.mjs';

export const GUIDES_DIR = 'docs/guides';
export const GUIDE_START = '<!-- generated by npm run guides from the skill and cycle.md: edit those, not this block -->';
export const README_START = '<!-- generated by npm run guides from cycle.md: edit that, not this block -->';
export const END = '<!-- end of the generated block -->';
const CYCLE_DIR = 'skills/method/references';
const CODE_SPAN = /(`+)(?:(?!\1).)+?\1/g;

// ---- Reading ------------------------------------------------------------------------------------

// A skill's parts, from its SKILL.md: the name and the description of its frontmatter, its title, and the lines of its
// "When to use" and its "Reads and writes", as written, with no blank line at either end. Headings count only outside
// fenced code, so a "## " line inside a fence belongs to its section.
export function skillParts(text) {
  const { fields, problems: frontmatterProblems } = parseFrontmatter(text);
  const problems = [...frontmatterProblems];
  const lines = text.split(/\r?\n/);
  const frontmatterEnd = lines[0] === '---' ? lines.indexOf('---', 1) + 1 : 0; // the line number of its closing ---
  let title = null;
  const headings = [];
  for (const [lineNo, line] of unfencedLines(text)) {
    if (lineNo <= frontmatterEnd) continue;
    const h1 = /^#\s+(.+?)\s*$/.exec(line)?.[1];
    if (h1 !== undefined && title === null) title = h1;
    const h2 = /^##\s+(.+?)\s*$/.exec(line)?.[1];
    if (h2 !== undefined) headings.push({ lineNo, heading: h2 });
  }
  const section = (heading) => {
    const at = headings.findIndex((h) => h.heading === heading);
    if (at < 0) {
      problems.push(`no "## ${heading}" section`);
      return [];
    }
    const body = lines.slice(headings[at].lineNo, at + 1 < headings.length ? headings[at + 1].lineNo - 1 : lines.length);
    while (body.length > 0 && !body[0].trim()) body.shift();
    while (body.length > 0 && !body.at(-1).trim()) body.pop();
    return body;
  };
  const name = typeof fields.name === 'string' ? fields.name : null;
  const description = typeof fields.description === 'string' ? fields.description : null;
  if (!name) problems.push('no name');
  if (!description) problems.push('no description');
  if (!title) problems.push('no title');
  const whenToUse = section('When to use');
  const readsAndWrites = section('Reads and writes');
  return { name, description, title, whenToUse, readsAndWrites, problems };
}

// The cycle's steps, from the first table of cycle.md that has a Step and a Skill column: each step's number, name and
// skill, and its "What it does", Runs and Next cells as written.
export function cycleRows(cycleText) {
  const table = tablesIn(cycleText).find((t) => t.header.includes('Step') && t.header.includes('Skill'));
  if (!table) return [];
  const cell = (row, name) => (table.header.indexOf(name) < 0 ? '' : row.cells[table.header.indexOf(name)] ?? '');
  return table.rows.map((row) => ({
    number: cellText(cell(row, '#')),
    step: cellText(cell(row, 'Step')),
    skill: cellText(cell(row, 'Skill')),
    does: cell(row, 'What it does'),
    runs: cell(row, 'Runs'),
    next: cell(row, 'Next'),
  }));
}

// ---- Writing ------------------------------------------------------------------------------------

// The path from one folder of the repository to a file of it, both written from the repository's root.
function relativePath(fromDir, to) {
  const from = fromDir === '.' || fromDir === '' ? [] : fromDir.split('/');
  const parts = to.split('/');
  let same = 0;
  while (same < from.length && same < parts.length && from[same] === parts[same]) same++;
  return [...Array(from.length - same).fill('..'), ...parts.slice(same)].join('/') || '.';
}

// A line whose relative links, written in a file of fromDir, are written again to point at the same files from toDir.
// A link inside a code span, or with a scheme, stays as it is; a link to a #fragment alone points into fromFile.
export function rebasedLine(line, fromDir, toDir = GUIDES_DIR, fromFile = posix.join(fromDir, 'SKILL.md')) {
  const masked = line.replace(CODE_SPAN, (span) => '\0'.repeat(span.length));
  const changes = [];
  for (const m of masked.matchAll(/(!?\[(?:[^\]\\]|\\.)*\]\(\s*)(<[^>]*>|[^\s)]+)/g)) {
    const start = m.index + m[1].length;
    const raw = line.slice(start, start + m[2].length);
    const bracketed = raw.startsWith('<') && raw.endsWith('>');
    const target = bracketed ? raw.slice(1, -1) : raw;
    if (!target || /^[a-z][a-z0-9+.-]*:/i.test(target) || target.startsWith('//')) continue;
    const hash = target.indexOf('#');
    const path = hash < 0 ? target : target.slice(0, hash);
    const fragment = hash < 0 ? '' : target.slice(hash);
    const file = path === '' ? fromFile : path.startsWith('/') ? posix.normalize(path.slice(1)) : posix.normalize(posix.join(fromDir, path));
    const moved = relativePath(toDir, file) + fragment;
    changes.push({ start, end: start + raw.length, text: bracketed ? `<${moved}>` : moved });
  }
  let out = line;
  for (const change of changes.reverse()) out = out.slice(0, change.start) + change.text + out.slice(change.end);
  return out;
}

// A line in which each code span that names one of the skills, but the skill itself, becomes a link to that skill's
// guide. A code span that is already a link's text stays as it is.
function linkedSkills(line, skills, own) {
  return line.replace(CODE_SPAN, (span, ticks, offset) => {
    const name = span.slice(ticks.length, -ticks.length).trim();
    const isLinkText = line[offset - 1] === '[' && line.startsWith('](', offset + span.length);
    return skills.includes(name) && name !== own && !isLinkText ? `[${span}](${name}.md)` : span;
  });
}

// A skill's guide's block, line by line: its title and description, its row in the cycle, and its "When to use" and
// "Reads and writes", word for word, with each relative link re-based and, in "When to use", each skill named linked.
// method and hello have no row in the cycle: they run at any time.
export function guideBlock(skill, parts, cycle, skills) {
  const row = cycle.find((r) => r.skill === skill);
  const fromCycle = (cellValue) => rebasedLine(cellValue, CYCLE_DIR, GUIDES_DIR, `${CYCLE_DIR}/cycle.md`);
  const fromSkill = (line) => rebasedLine(line, `skills/${skill}`);
  return [
    GUIDE_START,
    `# ${parts.title}`,
    '',
    `> ${parts.description}`,
    '',
    '| | |',
    '|---|---|',
    `| Skill | \`${skill}\`, [its file](${relativePath(GUIDES_DIR, `skills/${skill}/SKILL.md`)}) |`,
    ...(row
      ? [`| Step | ${row.number} of ${cycle.length}: ${row.step} |`, `| Runs | ${fromCycle(row.runs)} |`, `| Next | ${fromCycle(row.next)} |`]
      : ['| Step | none: it runs at any time |']),
    `| Call it | \`/gradatim:${skill}\` on Claude Code; [the other hosts](install.md#calling-a-skill) |`,
    '',
    '## When to use it',
    '',
    ...parts.whenToUse.map((line) => linkedSkills(fromSkill(line), skills, skill)),
    '',
    '## What it reads and writes',
    '',
    ...parts.readsAndWrites.map(fromSkill),
    '',
    END,
  ];
}

// The README's block: the cycle's table, one row a step, each skill linked to its guide.
export function readmeBlock(cycle) {
  return [
    README_START,
    '',
    '| # | Step | Skill | What it does |',
    '|---|---|---|---|',
    ...cycle.map(
      (row) => `| ${row.number} | ${row.step} | [\`${row.skill}\`](${GUIDES_DIR}/${row.skill}.md) | ${rebasedLine(row.does, CYCLE_DIR, '.', `${CYCLE_DIR}/cycle.md`)} |`,
    ),
    '',
    END,
  ];
}

// ---- A block in a file --------------------------------------------------------------------------

// Each line of a text, with where it starts and ends, its line break included, and its text without the break.
function linesOf(text) {
  const lines = [];
  let start = 0;
  for (;;) {
    const nl = text.indexOf('\n', start);
    const end = nl < 0 ? text.length : nl + 1;
    lines.push({ start, end, line: text.slice(start, nl < 0 ? text.length : nl).replace(/\r$/, '') });
    if (nl < 0) return lines;
    start = end;
  }
}

// Where a text's block lies: the index of its start marker's line and of its end marker's, or the problem. A guide's
// block opens on line 1 (first). Markers are read with trailing spaces off.
export function blockSpan(text, start, { first = false } = {}) {
  const lines = linesOf(text);
  const at = (marker) => lines.flatMap((l, i) => (l.line.trimEnd() === marker ? [i] : []));
  const starts = at(start);
  const ends = at(END);
  if (starts.length === 0) return { problem: 'no start marker' };
  if (starts.length > 1 || ends.length > 1) return { problem: 'its markers are doubled' };
  if (ends.length === 0 || ends[0] < starts[0]) return { problem: 'no end marker after its start marker' };
  if (first && starts[0] !== 0) return { problem: "line 1 isn't its start marker" };
  return { lines, from: starts[0], to: ends[0] };
}

// The text with its block replaced by the given lines, the text above and below it kept byte for byte; or the problem,
// where its markers are missing or doubled.
export function withBlock(text, block, start, options) {
  const span = blockSpan(text, start, options);
  if (span.problem) return { problem: span.problem };
  const { lines, from, to } = span;
  return { text: `${text.slice(0, lines[from].start)}${block.join('\n')}\n${text.slice(lines[to].end)}` };
}

// ---- The check ----------------------------------------------------------------------------------

const normal = (line) => line.replace(/\s+$/, '');

// The first line, counted from 1, where a text's block differs from the lines it should hold, after CRLF to LF and
// trailing spaces off; or 0 where they agree.
function staleLine(span, expected) {
  const actual = span.lines.slice(span.from, span.to + 1).map((l) => normal(l.line));
  const wanted = expected.map(normal);
  for (let i = 0; i < Math.max(actual.length, wanted.length); i++) if (actual[i] !== wanted[i]) return span.from + Math.min(i, actual.length - 1) + 1;
  return 0;
}

// What is wrong with the guides and the README's table, each problem with where it is and what it is, in order of
// where. skills maps each skill in skills/ to its SKILL.md's text, guides each file in docs/guides/ to its text, and
// readme is README.md's text, or null. The rules: every skill has its guide (1); no other file holds a guide's block (2);
// a guide's block opens on line 1 and its end marker follows once (3); each block, a guide's (4) and the README's (5),
// is what the script writes now; and no guide links a planning doc, in docs/ outside docs/guides/ (6).
export function guideProblems({ skills, cycleText, guides, readme }) {
  const problems = [];
  const cycle = cycleRows(cycleText);
  const names = [...skills.keys()];
  for (const [skill, text] of skills) {
    const file = `${GUIDES_DIR}/${skill}.md`;
    const parts = skillParts(text);
    for (const problem of parts.problems) problems.push({ where: `skills/${skill}/SKILL.md`, what: `its guide can't be written: ${problem}` });
    if (!guides.has(`${skill}.md`)) {
      problems.push({ where: file, what: 'missing: every skill has its guide. Run npm run guides' });
      continue;
    }
    const span = blockSpan(guides.get(`${skill}.md`), GUIDE_START, { first: true });
    if (span.problem) {
      problems.push({ where: file, what: `no generated block: ${span.problem}. Line 1 opens it, and its end marker follows once; then run npm run guides` });
      continue;
    }
    const line = staleLine(span, guideBlock(skill, parts, cycle, names));
    if (line) problems.push({ where: `${file}:${line}`, what: `its block differs from what npm run guides writes now, from its skill and cycle.md: run npm run guides` });
  }
  for (const [name, text] of guides)
    if (!names.includes(name.replace(/\.md$/, '')) && linesOf(text).some((l) => l.line.trimEnd() === GUIDE_START))
      problems.push({ where: `${GUIDES_DIR}/${name}`, what: 'holds a guide\'s generated block, and is named after no skill: a skill renamed or removed leaves its guide to delete by hand' });
  const span = readme === null ? { problem: 'no README.md' } : blockSpan(readme, README_START);
  if (span.problem) problems.push({ where: 'README.md', what: `no table of the cycle: ${span.problem}` });
  else {
    const line = staleLine(span, readmeBlock(cycle));
    if (line) problems.push({ where: `README.md:${line}`, what: 'its table of the cycle differs from what npm run guides writes now, from cycle.md: run npm run guides' });
  }
  for (const [name, text] of guides)
    for (const { lineNo, raw, path } of relativeLinks(text)) {
      if (path === '') continue;
      const target = path.startsWith('/') ? posix.normalize(path.slice(1)) : posix.normalize(posix.join(GUIDES_DIR, path));
      if ((target === 'docs' || target.startsWith('docs/')) && target !== GUIDES_DIR && !target.startsWith(`${GUIDES_DIR}/`))
        problems.push({ where: `${GUIDES_DIR}/${name}:${lineNo}`, what: `links ${raw}, a planning doc: the guides stand apart from docs/ outside docs/guides/` });
    }
  return problems.sort((a, b) => a.where.localeCompare(b.where, 'en', { numeric: true }));
}

// ---- The CLI ------------------------------------------------------------------------------------

function main() {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const skillsDir = join(root, 'skills');
  const skills = readdirSync(skillsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith('.') && existsSync(join(skillsDir, entry.name, 'SKILL.md')))
    .map((entry) => entry.name)
    .sort();
  const cycle = cycleRows(readFileSync(join(root, CYCLE_DIR, 'cycle.md'), 'utf8'));
  const writes = [];
  const problems = [];
  let created = 0;
  for (const skill of skills) {
    const at = `${GUIDES_DIR}/${skill}.md`;
    const parts = skillParts(readFileSync(join(skillsDir, skill, 'SKILL.md'), 'utf8'));
    if (parts.problems.length > 0) {
      problems.push(`skills/${skill}/SKILL.md  ${parts.problems.join('; ')}`);
      continue;
    }
    const block = guideBlock(skill, parts, cycle, skills);
    const file = join(root, GUIDES_DIR, `${skill}.md`);
    if (!existsSync(file)) {
      created++;
      writes.push({ file, at, text: `${block.join('\n')}\n`, old: null });
      continue;
    }
    const old = readFileSync(file, 'utf8');
    const result = withBlock(old, block, GUIDE_START, { first: true });
    if (result.problem) problems.push(`${at}  ${result.problem}`);
    else writes.push({ file, at, text: result.text, old });
  }
  const readmeFile = join(root, 'README.md');
  const readme = existsSync(readmeFile) ? readFileSync(readmeFile, 'utf8') : '';
  const result = withBlock(readme, readmeBlock(cycle), README_START);
  if (result.problem) problems.push(`README.md  ${result.problem}`);
  else writes.push({ file: readmeFile, at: 'README.md', text: result.text, old: readme });
  if (problems.length > 0) {
    for (const problem of problems) console.log(`error    ${problem}`);
    console.log('Wrote nothing: fix the markers, then run it again. Line 1 of a guide opens its block, and its end marker follows once.');
    process.exitCode = 1;
    return;
  }
  const changed = writes.filter((w) => w.text !== w.old);
  for (const w of changed) {
    if (w.old === null) mkdirFor(w.file);
    writeFileSync(w.file, w.text);
  }
  console.log(`${skills.length} guides and the README's table: ${created} created, ${changed.length - created} updated, ${writes.length - changed.length} already current.`);
}

function mkdirFor(file) {
  const dir = dirname(file);
  if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
}

// Whether node started this file, through a symlink or a junction too, as the runner checks.
function startedHere() {
  try {
    return Boolean(process.argv[1]) && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}
if (startedHere()) main();
